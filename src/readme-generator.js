import { writeFile } from 'node:fs/promises';

/**
 * Generate README.md from classification state.
 * Groups repos by their first category, with an overview table at the top.
 * @param {object} state - classification state { last_run, total_classified, repos }
 * @param {string} outputPath - file path to write README.md
 */
export async function generateReadme(state, outputPath) {
  const { last_run, total_classified, repos } = state;

  // Group repos by first category
  const grouped = {};
  for (const [fullName, repo] of Object.entries(repos)) {
    const category = repo.categories?.[0] || 'Other';
    if (!grouped[category]) {
      grouped[category] = [];
    }
    grouped[category].push({ fullName, ...repo });
  }

  // Sort categories alphabetically, repos within each category by stars descending
  const sortedCategories = Object.keys(grouped).sort();
  for (const cat of sortedCategories) {
    grouped[cat].sort((a, b) => (b.stargazers_count || 0) - (a.stargazers_count || 0));
  }

  const dateStr = last_run ? new Date(last_run).toISOString().split('T')[0] : 'N/A';

  const lines = [];

  // Header
  lines.push('# [⭐ GitHub Star Classifier](https://coreycao.github.io/gitstar-auto-classifier/)');
  lines.push('');
  lines.push(`> Automatically classified GitHub starred repositories using LLM.`);
  lines.push(`> Last updated: ${dateStr} | Total: **${total_classified}** repos across **${sortedCategories.length}** categories`);
  lines.push('');

  // Overview table
  lines.push('## 📊 Overview');
  lines.push('');
  lines.push('| Category | Count |');
  lines.push('|---|---|');
  for (const cat of sortedCategories) {
    lines.push(`| ${cat} | ${grouped[cat].length} |`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  // Per-category sections
  for (const cat of sortedCategories) {
    lines.push(`## ${cat}`);
    lines.push('');
    lines.push('| Repository | Summary | Language | ⭐ |');
    lines.push('|---|---|---|---|');

    for (const repo of grouped[cat]) {
      const name = repo.fullName;
      const link = `[${name}](${repo.html_url})`;
      const summary = escapeMarkdown(repo.summary || repo.description || '');
      const lang = repo.language || '-';
      const stars = formatStars(repo.stargazers_count);

      lines.push(`| ${link} | ${summary} | ${lang} | ${stars} |`);
    }

    lines.push('');
  }

  // Footer
  lines.push('---');
  lines.push('');
  lines.push(`_Generated by [gitstar-auto-classifier](https://github.com/user/gitstar-auto-classifier) — ${total_classified} repositories classified._`);
  lines.push('');

  await writeFile(outputPath, lines.join('\n'), 'utf-8');
}

/**
 * Format star count with k suffix for thousands.
 */
function formatStars(count) {
  if (!count) return '0';
  if (count >= 1000) {
    return `${(count / 1000).toFixed(1)}k`;
  }
  return String(count);
}

/**
 * Escape pipe characters and other special markdown in table cells.
 */
function escapeMarkdown(text) {
  return text
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ')
    .replace(/\r/g, '')
    .slice(0, 200); // Truncate long descriptions for table readability
}
