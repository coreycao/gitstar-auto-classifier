import { writeFile } from 'node:fs/promises';

/**
 * Generate README.md from classification state.
 * Groups repos by their first category, with an overview table at the top.
 * @param {object} state - classification state { last_run, total_classified, repos }
 * @param {string} outputPath - file path to write README.md
 */
export async function generateReadme(state, outputPath, options = {}) {
  const { last_run, total_classified, repos } = state;
  const repoUrl = options.repoUrl || 'https://github.com/your-username/gitstar-auto-classifier';
  const pagesUrl = options.pagesUrl || '';
  // Title links to the Pages site when known, otherwise to the repo.
  const titleUrl = pagesUrl || repoUrl;

  // Group repos by first category
  const grouped = {};
  for (const [fullName, repo] of Object.entries(repos)) {
    const category = repo.categories?.[0] || 'Other';
    if (!grouped[category]) {
      grouped[category] = [];
    }
    grouped[category].push({ fullName, ...repo });
  }

  // Sort categories alphabetically, repos within each category by stars descending
  const sortedCategories = Object.keys(grouped).sort();
  for (const cat of sortedCategories) {
    grouped[cat].sort((a, b) => (b.stargazers_count || 0) - (a.stargazers_count || 0));
  }

  const dateStr = last_run ? new Date(last_run).toISOString().split('T')[0] : 'N/A';

  const lines = [];

  // Header
  lines.push(`# [⭐ GitHub Star Classifier](${titleUrl})`);
  lines.push('');
  lines.push(`> Automatically classified GitHub starred repositories using LLM.`);
  lines.push(`> Last updated: ${dateStr} | Total: **${total_classified}** repos across **${sortedCategories.length}** categories`);
  lines.push('');

  // Setup / fork instructions (owner-independent, so they survive regeneration).
  // Placed at the top so they're the first thing readers see.
  lines.push('## 🔧 Run It On Your Own Account');
  lines.push('');
  lines.push('This project auto-classifies **your** GitHub starred repos and publishes a searchable site via GitHub Pages.');
  lines.push('');
  lines.push('1. **Fork** this repository.');
  lines.push('2. Enable Actions: *Settings → Actions → Allow all actions*.');
  lines.push('3. Add repository **Secret** `LLM_API_KEY` (your LLM API key), and repo **Variables** `LLM_BASE_URL` (any OpenAI-compatible endpoint, e.g. `https://api.deepseek.com`) and `LLM_MODEL` (e.g. `deepseek-chat`).');
  lines.push('4. Enable Pages: *Settings → Pages → Source → GitHub Actions*.');
  lines.push('5. Run the workflow: *Actions → "Classify Starred Repos" → Run workflow*. The weekly schedule (Mon 03:00 UTC) activates after the first run.');
  lines.push('');
  lines.push('`GH_USERNAME` defaults to your account automatically; set it as a repo **Variable** to classify someone else\'s stars.');
  lines.push('');
  lines.push('---');
  lines.push('');

  // Overview table
  lines.push('## 📊 Overview');
  lines.push('');
  lines.push('| Category | Count |');
  lines.push('|---|---|');
  for (const cat of sortedCategories) {
    lines.push(`| ${cat} | ${grouped[cat].length} |`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  // Per-category sections
  for (const cat of sortedCategories) {
    lines.push(`## ${cat}`);
    lines.push('');
    lines.push('| Repository | Summary | Language | ⭐ |');
    lines.push('|---|---|---|---|');

    for (const repo of grouped[cat]) {
      const name = repo.fullName;
      const link = `[${name}](${repo.html_url})`;
      const summary = escapeMarkdown(repo.summary || repo.description || '');
      const lang = repo.language || '-';
      const stars = formatStars(repo.stargazers_count);

      lines.push(`| ${link} | ${summary} | ${lang} | ${stars} |`);
    }

    lines.push('');
  }

  // Footer
  lines.push('---');
  lines.push('');
  lines.push(`_Generated by [gitstar-auto-classifier](${repoUrl}) — ${total_classified} repositories classified._`);
  lines.push('');

  await writeFile(outputPath, lines.join('\n'), 'utf-8');
}

/**
 * Format star count with k suffix for thousands.
 */
function formatStars(count) {
  if (!count) return '0';
  if (count >= 1000) {
    return `${(count / 1000).toFixed(1)}k`;
  }
  return String(count);
}

/**
 * Escape pipe characters and other special markdown in table cells.
 */
function escapeMarkdown(text) {
  return text
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ')
    .replace(/\r/g, '')
    .slice(0, 200); // Truncate long descriptions for table readability
}
